import { getAwsSecretValue } from 'get-env';
import { NewConversationInfo } from '../models';
import { dynamoProvider, sfnProvider, sqsProvider } from '../providers';
import {
  PAGE_INDEX,
  SQS_ID_DELIMITER,
  TASK_TOKEN_INDEX,
  TENANT_INDEX,
} from '../utils/constants';
import logger from '../utils/logger';
import stringToHash from '../utils/string';
import { SaleAssignmentRepository } from './interfaces/SaleAssignmentRepository';

export default class SaleAssignmentRepositoryImpl implements SaleAssignmentRepository {
  /**
   * Notify message to automation module that the system has received new conversation
   * System will trigger AWS StepFunctions to execute sale assignment process
   * @param conversationInfor New conversation information
   * including tenant, paltform, conversationid, pageid
   */
  notifyNewIncomingConversation = async (conversationInfor: NewConversationInfo) => {
    // Queue endpoint
    const queueUrl = await getAwsSecretValue('NEW_CONVERSATION_QUEUE_ENDPOINT');
    // Body data
    const queueMessageBody = JSON.stringify(conversationInfor);
    const messageAttributes: { [key: string]: any } = {};
    Object.entries(conversationInfor).forEach(([key, item]) => {
      messageAttributes[`${key}`] = {
        DataType: 'String',
        StringValue: item,
      };
    });
    const { pageId, chatPlatform } = conversationInfor;
    const sendMessageRequest = {
      /**
       * Queue endpoint
       */
      QueueUrl: queueUrl,
      /**
       * Message body json string
       */
      MessageBody: queueMessageBody,
      MessageAttributes: messageAttributes,
      /**
       * This parameter applies only to FIFO (first-in-first-out) queues.
       * The token used for deduplication of sent messages.
       */
      MessageDeduplicationId: stringToHash(conversationInfor.conversationId),
      /**
       * This parameter applies only to FIFO (first-in-first-out) queues.
       */
      MessageGroupId: `${pageId}${SQS_ID_DELIMITER}${chatPlatform.toUpperCase()}`,
    };
    const queueMessage = await sqsProvider.sendMessage(sendMessageRequest);
    logger.log(`A new SQS message has been pushed with data ${JSON.stringify(queueMessage, null, 4)}`);
  };

  /**
   * Delete message in queue when sale automation process started
   * The automation process is handled by AWS StepFunctions
   * @param receiptHandler Receipt handler of queue message to delete
   * @returns
   */
  onSaleAssignmentAutoProcessStarted = async (
    receiptHandler: string,
  ) => {
    const queueUrl = await getAwsSecretValue('NEW_CONVERSATION_QUEUE_ENDPOINT');
    await sqsProvider.deleteMessage(queueUrl, receiptHandler);
  };

  /**
   * Start auto assignment workflows by triggering AWS StepFunctions
   * @param stateMachineArn Sfn arn
   * @param name Name of execution
   * @param payload Execution payload data JSON
   */
  startSaleAssignmentSfnWorkflow = async (
    stateMachineArn: string,
    name: string,
    payload: string,
  ) => {
    const input = { stateMachineArn, name, input: payload };
    await sfnProvider.startExecution(input);
  };

  /**
   * Handle on sent message to customer
   * This function do following steps:
   * 1. Get conversation with task token stored at DynamoDB
   * 2. Send task success api to AWS StepFunctions
   * @param tenant Tenant id
   * @param chatPlatform Chat platform
   * @param pageId Page id
   * @param conversationId Conversation id
   */
  onSentMessageToCustomer = async (
    tenant: string,
    chatPlatform: string,
    pageId: string,
    conversationId: string,
  ) => {
    // Chat table
    const ddbChatTable = await getAwsSecretValue('DYNAMO_CHAT_TABLE');

    // Get task token attached to conversation
    const taskTokenItem = await dynamoProvider.getItem(
      ddbChatTable,
      `${TENANT_INDEX}#${tenant}#${PAGE_INDEX}#${chatPlatform.toUpperCase()}#${pageId}`,
      `${TASK_TOKEN_INDEX}#${conversationId}`,
    );

    // Send task success if needed
    if (taskTokenItem) {
      const { taskToken } = taskTokenItem;
      const input = { taskToken, output: '{}' };
      await sfnProvider.sendTaskSuccess(input);
    }
  };

  /**
   * Store task token that linked to conversation
   * Task token is generated by StepFunctions
   * Then, it will be used to mark as process is finished for the next steps
   * @param tenant Tenant id
   * @param chatPlatform Chat platform
   * @param pageId Page id
   * @param conversationId Conversation id
   */
  storeSfnTaskToken = async (
    tenant: string,
    chatPlatform: string,
    pageId: string,
    conversationId: string,
    taskToken: string,
  ) => {
    // Chat table
    const ddbChatTable = await getAwsSecretValue('DYNAMO_CHAT_TABLE');

    // Get task token attached to conversation
    const taskTokenItem = await dynamoProvider.putItem(
      ddbChatTable,
      `${TENANT_INDEX}#${tenant}#${PAGE_INDEX}#${chatPlatform.toUpperCase()}#${pageId}`,
      `${TASK_TOKEN_INDEX}#${conversationId}`,
      { taskToken },
    );

    logger.log(`Stored task token successfully, result is ${JSON.stringify(taskTokenItem, null, 2)}`);
  };
}
